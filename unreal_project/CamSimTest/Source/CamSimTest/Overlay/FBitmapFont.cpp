// -----------------------------------------------------------------------------
// SetPixel — write a single pixel with bounds check
// -----------------------------------------------------------------------------
void FBitmapFont::SetPixel(TArray<FColor>& Pixels, int32 BufW, int32 BufH, int32 X, int32 Y, FColor C)
{
    if (X < 0 || Y < 0 || X >= BufW || Y >= BufH)
    {
        return;
    }
    Pixels[Y * BufW + X] = C;
}

// -----------------------------------------------------------------------------
// DrawHLine — horizontal line from (X,Y) for Len pixels
// -----------------------------------------------------------------------------
void FBitmapFont::DrawHLine(TArray<FColor>& Pixels, int32 BufW, int32 BufH, int32 X, int32 Y, int32 Len, FColor C)
{
    for (int32 I = 0; I < Len; ++I)
    {
        SetPixel(Pixels, BufW, BufH, X + I, Y, C);
    }
}

// -----------------------------------------------------------------------------
// DrawVLine — vertical line from (X,Y) for Len pixels
// -----------------------------------------------------------------------------
void FBitmapFont::DrawVLine(TArray<FColor>& Pixels, int32 BufW, int32 BufH, int32 X, int32 Y, int32 Len, FColor C)
{
    for (int32 I = 0; I < Len; ++I)
    {
        SetPixel(Pixels, BufW, BufH, X, Y + I, C);
    }
}

// -----------------------------------------------------------------------------
// DrawRect — unfilled rectangle outline
// -----------------------------------------------------------------------------
void FBitmapFont::DrawRect(TArray<FColor>& Pixels, int32 BufW, int32 BufH, int32 X, int32 Y, int32 W, int32 H, FColor C)
{
    DrawHLine(Pixels, BufW, BufH, X,         Y,         W, C); // top
    DrawHLine(Pixels, BufW, BufH, X,         Y + H - 1, W, C); // bottom
    DrawVLine(Pixels, BufW, BufH, X,         Y,         H, C); // left
    DrawVLine(Pixels, BufW, BufH, X + W - 1, Y,         H, C); // right
}

// -----------------------------------------------------------------------------
// FillRect — solid filled rectangle
// -----------------------------------------------------------------------------
void FBitmapFont::FillRect(TArray<FColor>& Pixels, int32 BufW, int32 BufH, int32 X, int32 Y, int32 W, int32 H, FColor C)
{
    for (int32 Row = 0; Row < H; ++Row)
    {
        DrawHLine(Pixels, BufW, BufH, X, Y + Row, W, C);
    }
}

// -----------------------------------------------------------------------------
// DrawChar — render a single character at (X,Y), returns X advanced by CharStride*Scale
// -----------------------------------------------------------------------------
int32 FBitmapFont::DrawChar(TArray<FColor>& Pixels, int32 BufW, int32 BufH,
                             int32 X, int32 Y, char Ch,
                             FColor Fg, int32 Scale)
{
    const int32 Advance = CharStride * Scale;

    // Out-of-range character: skip rendering but still advance cursor
    if ((uint8)Ch < 0x20 || (uint8)Ch > 0x7E)
    {
        return X + Advance;
    }

    const uint8* Glyph = GFont5x7[(uint8)Ch - 0x20];

    for (int32 Row = 0; Row < GlyphH; ++Row)
    {
        for (int32 Col = 0; Col < GlyphW; ++Col)
        {
            if (Glyph[Row] & (0x10 >> Col))
            {
                // Fill a Scale x Scale block for this glyph pixel
                const int32 PX = X + Col * Scale;
                const int32 PY = Y + Row * Scale;
                for (int32 SY = 0; SY < Scale; ++SY)
                {
                    for (int32 SX = 0; SX < Scale; ++SX)
                    {
                        SetPixel(Pixels, BufW, BufH, PX + SX, PY + SY, Fg);
                    }
                }
            }
        }
    }

    return X + Advance;
}

// -----------------------------------------------------------------------------
// DrawString — render a null-terminated string, returns final X position
// -----------------------------------------------------------------------------
int32 FBitmapFont::DrawString(TArray<FColor>& Pixels, int32 BufW, int32 BufH,
                               int32 X, int32 Y, const ANSICHAR* Str,
                               FColor Fg, int32 Scale)
{
    if (!Str)
    {
        return X;
    }

    int32 CurX = X;
    while (*Str)
    {
        CurX = DrawChar(Pixels, BufW, BufH, CurX, Y, *Str, Fg, Scale);
        ++Str;
    }
    return CurX;
}

// -----------------------------------------------------------------------------
// DrawStringWithShadow — render string with a 1-pixel black drop shadow
// -----------------------------------------------------------------------------
int32 FBitmapFont::DrawStringWithShadow(TArray<FColor>& Pixels, int32 BufW, int32 BufH,
                                         int32 X, int32 Y, const ANSICHAR* Str,
                                         FColor Fg, int32 Scale)
{
    // Shadow pass: black at (X+1, Y+1)
    DrawString(Pixels, BufW, BufH, X + 1, Y + 1, Str, FColor(0, 0, 0, 255), Scale);
    // Foreground pass: Fg at (X, Y)
    return DrawString(Pixels, BufW, BufH, X, Y, Str, Fg, Scale);
}

// -----------------------------------------------------------------------------
// StringWidth — pixel width of a string (does not include trailing spacing)
// -----------------------------------------------------------------------------
int32 FBitmapFont::StringWidth(const ANSICHAR* Str, int32 Scale)
{
    if (!Str || *Str == '\0')
    {
        return 0;
    }

    int32 Count = 0;
    while (*Str++)
    {
        ++Count;
    }
    return Count * CharStride * Scale;
}
